package com.tkisor.nekojs.probe.backend.typescript;

import com.tkisor.nekojs.api.catalog.ManualDeclarationCatalogEntry;
import com.tkisor.nekojs.api.surface.ApiTypeRef;
import com.tkisor.nekojs.probe.ProbeContext;
import com.tkisor.nekojs.probe.ir.TypeReflector;
import com.tkisor.nekojs.probe.ir.TypeScriptClassRenderer;
import com.tkisor.nekojs.probe.types.TypeAliasRegistry;

import java.util.Collections;
import java.util.LinkedHashSet;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

/** Resolves explicit authored aliases without parsing arbitrary TypeScript or widening the primary scan. */
final class ManualDeclarationReferences {
    private record Reference(String owner, ManualDeclarationCatalogEntry.TypeReference type) {}

    private final Map<String, Reference> references = new TreeMap<>();

    static ManualDeclarationReferences prepare(ProbeContext context, Set<String> classes,
                                                TypeScriptDeclarationClosure closure) {
        var result = new ManualDeclarationReferences();
        if (context.snapshot().manualDeclarations() == null) return result;
        for (var entry : context.snapshot().manualDeclarations()) {
            if (entry.declaration() == null || entry.declaration().isBlank()) continue;
            for (var alias : new TreeMap<>(entry.references()).entrySet()) {
                var reference = new Reference(entry.id(), alias.getValue());
                Reference previous = result.references.putIfAbsent(alias.getKey(), reference);
                if (previous != null && !previous.type().equals(reference.type())) {
                    throw new IllegalArgumentException("[NEKO-4051] Manual declaration reference rejected: alias '"
                            + alias.getKey() + "' conflicts between " + previous.owner() + " and " + entry.id());
                }
                Class<?> target = declarationTarget(reference.type().targetType());
                if (target == null) continue;
                String dependency = target.getName();
                closure.includeReference(classes, dependency);
                if (closure.unavailable().containsKey(dependency)) throw unavailable(reference);
            }
        }
        return result;
    }

    void validateGeneratedTypes(IndexFileGenerator generator) {
        for (Reference reference : references.values()) {
            Class<?> target = declarationTarget(reference.type().targetType());
            if (target != null && !generator.hasDeclaration(target.getName())) throw unavailable(reference);
        }
    }

    String render(TypeAliasRegistry aliases) {
        if (references.isEmpty()) return "";
        TypeAliasRegistry inline = aliases.withReferences((fqn, name) -> {
            int separator = fqn.lastIndexOf('.');
            String module = "java:" + fqn.substring(0, separator).replace('.', '/');
            return "import(\"" + module + "\")." + name;
        });
        var output = new StringBuilder("// Auto-generated by NekoJS probe. Explicit manual type references.\n\n");
        for (var entry : references.entrySet()) {
            var type = entry.getValue().type();
            String rendered;
            if (type.input()) {
                rendered = FunctionalInterfaceAliasGenerator.renderJavaTypeInput(type.targetType(), inline,
                        new LinkedHashSet<>());
            } else {
                rendered = TypeScriptClassRenderer.renderTypeRef(rawHostRef(type.targetType()), inline, false);
            }
            output.append("type ").append(entry.getKey()).append(" = ").append(rendered).append(";\n");
        }
        return output.toString();
    }

    private static Class<?> declarationTarget(Class<?> type) {
        while (type.isArray()) type = type.getComponentType();
        return TypeReflector.toRef(type).kind() == ApiTypeRef.Kind.SYMBOL ? type : null;
    }

    private static ApiTypeRef rawHostRef(Class<?> type) {
        if (type.isArray()) return ApiTypeRef.array(rawHostRef(type.getComponentType()));
        ApiTypeRef reference = TypeReflector.toRef(type);
        // A Class reference denotes an actual raw Java use site, preserving the existing erasure rule.
        int parameterCount = com.tkisor.nekojs.core.reflect.JavaGenericTypes.parameters(type).size();
        if (reference.kind() == ApiTypeRef.Kind.SYMBOL && parameterCount > 0) {
            return new ApiTypeRef(reference.kind(), reference.name(), Collections.nCopies(
                    parameterCount, ApiTypeRef.primitive("any")), null);
        }
        return reference;
    }

    private static IllegalArgumentException unavailable(Reference reference) {
        return new IllegalArgumentException("[NEKO-4033] Manual declaration generation rejected for "
                + reference.owner() + "; required type is unavailable, excluded, or hidden: "
                + reference.type().targetType().getName());
    }
}
