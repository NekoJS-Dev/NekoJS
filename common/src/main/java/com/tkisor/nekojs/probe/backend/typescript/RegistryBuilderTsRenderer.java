package com.tkisor.nekojs.probe.backend.typescript;

import com.tkisor.nekojs.api.catalog.RegistryBuilderSurfaceEntry;

import java.util.List;

/**
 * Renders typed Builder entries as TS declarations. The input is {@link RegistryBuilderSurfaceEntry},
 * derived by contract reflection over the version tree. The Python side,
 * {@code RegistryBuilderPyRenderer}, renders from the <b>same</b> entry list, so members mean the same
 * thing on both sides. {@link TypeScriptProbeBackend} and the contract/golden tests share this renderer.
 */
public final class RegistryBuilderTsRenderer {

    private RegistryBuilderTsRenderer() {}

    /** Keeps explicitly scoped event builders separate from legacy global interfaces. */
    static String renderEventDependencies(List<RegistryBuilderSurfaceEntry> entries) {
        var groups = new java.util.LinkedHashMap<String, java.util.List<RegistryBuilderSurfaceEntry>>();
        for (var entry : entries) {
            String namespace = entry.eventPayload().typescriptBuilderNamespace();
            groups.computeIfAbsent(namespace == null ? "" : namespace, ignored -> new java.util.ArrayList<>()).add(entry);
        }
        StringBuilder output = new StringBuilder();
        groups.forEach((namespace, builders) -> {
            String declaration = render(builders);
            if (namespace.isEmpty()) {
                output.append(declaration);
            } else {
                output.append("declare namespace ").append(namespace).append(" {\n");
                var sugarNames = builders.stream().flatMap(builder -> builder.eventPayload().members().stream())
                        .map(member -> member.name()).filter(name -> !name.equals("custom") && !name.equals("register"))
                        .distinct().sorted().map(name -> "\"" + name + "\"").toList();
                output.append("    type RegistrySugar = ")
                        .append(sugarNames.isEmpty() ? "never" : String.join(" | ", sugarNames)).append(";\n\n");
                declaration.lines().forEach(line -> output.append(line.isEmpty() ? "" : "    " + line).append('\n'));
                output.append("}\n\n");
            }
        });
        return output.toString();
    }

    /**
     * Renders the content of {@code @registry-builders/index.d.ts}; an empty list returns an empty string.
     */
    public static String render(List<RegistryBuilderSurfaceEntry> entries) {
        if (entries == null || entries.isEmpty()) {
            return "";
        }
        StringBuilder sb = new StringBuilder();
        sb.append("// Auto-generated by NekoJS probe. Derived from RegistryBuilderContract reflection over the builder classes (ticket 15).\n");
        sb.append("// Do not edit; regenerate with /nekojs probe.\n\n");
        appendEntries(sb, entries, new java.util.HashSet<>());
        return sb.toString();
    }

    private static void appendEntries(StringBuilder sb, List<RegistryBuilderSurfaceEntry> entries, java.util.Set<String> rendered) {
        for (RegistryBuilderSurfaceEntry entry : entries) {
            if (!rendered.add(entry.builderName())) continue;
            sb.append("/** ").append(entry.builderName())
                    .append(" — registry '").append(entry.registryKey()).append('\'')
                    .append(", type '").append(entry.typeName()).append('\'');
            if (entry.sugarName() != null && !entry.sugarName().isEmpty()) {
                sb.append(", sugar '").append(entry.sugarName()).append('\'');
            }
            sb.append(". */\n");
            sb.append("interface ").append(entry.builderName()).append(" {\n");
            for (RegistryBuilderSurfaceEntry.Member member : entry.members()) {
                switch (member.kind()) {
                    case WRITABLE_PROPERTY -> sb.append("    ").append(member.name()).append(": ")
                            .append(member.tsType()).append(";\n");
                    case READ_ONLY_PROPERTY -> sb.append("    readonly ").append(member.name()).append(": ")
                            .append(member.tsType()).append(";\n");
                    case METHOD -> sb.append("    ").append(member.tsType()).append(";\n");
                }
            }
            sb.append("}\n\n");
        }
        var nested = entries.stream().flatMap(entry -> entry.nestedBuilders().stream()).distinct().toList();
        if (!nested.isEmpty()) {
            appendEntries(sb, nested, rendered);
        }
    }
}
