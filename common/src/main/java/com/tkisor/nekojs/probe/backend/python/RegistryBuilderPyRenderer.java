package com.tkisor.nekojs.probe.backend.python;

import com.tkisor.nekojs.api.catalog.RegistryBuilderSurfaceEntry;

import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * Renders typed Builder contract entries into Python declarations.
 * Input is a {@link RegistryBuilderSurfaceEntry}, the same entry list the TS side
 * {@code RegistryBuilderTsRenderer} consumes, so member semantics match on both sides.
 * Member names stay verbatim to the JS side ({@code maxStackSize}/{@code setMaxStackSize}).
 * {@link PythonProbeBackend} and the contract/golden tests share this renderer.
 */
public final class RegistryBuilderPyRenderer {

    private RegistryBuilderPyRenderer() {}

    /**
     * Renders the content of {@code nekojs/_registry_builders/__init__.pyi}; returns an empty string for an empty
     * list.
     */
    public static String render(List<RegistryBuilderSurfaceEntry> entries) {
        if (entries == null || entries.isEmpty()) {
            return "";
        }
        StringBuilder sb = new StringBuilder();
        sb.append("# Auto-generated by NekoJS probe. Derived from RegistryBuilderContract reflection over the builder classes (ticket 15).\n");
        sb.append("# Do not edit; regenerate with /nekojs probe.\n\n");
        sb.append("from typing import Any, Callable, Protocol, overload\n\n");
        appendEntries(sb, entries, new java.util.HashSet<>());
        return sb.toString();
    }

    private static void appendEntries(StringBuilder sb, List<RegistryBuilderSurfaceEntry> entries, java.util.Set<String> rendered) {
        for (RegistryBuilderSurfaceEntry entry : entries) {
            if (!rendered.add(entry.builderName())) continue;
            sb.append("# ").append(entry.builderName())
                    .append(" — registry '").append(entry.registryKey()).append('\'')
                    .append(", type '").append(entry.typeName()).append('\'');
            if (entry.sugarName() != null && !entry.sugarName().isEmpty()) {
                sb.append(", sugar '").append(entry.sugarName()).append('\'');
            }
            sb.append("\nclass ").append(entry.builderName()).append("(Protocol):\n");
            Map<String, Long> methodCounts = entry.members().stream()
                    .filter(member -> member.kind() == RegistryBuilderSurfaceEntry.MemberKind.METHOD)
                    .collect(Collectors.groupingBy(RegistryBuilderSurfaceEntry.Member::name, Collectors.counting()));
            for (RegistryBuilderSurfaceEntry.Member member : entry.members()) {
                switch (member.kind()) {
                    case WRITABLE_PROPERTY -> sb.append("    ").append(member.name()).append(": ")
                            .append(member.pyType()).append("\n");
                    case READ_ONLY_PROPERTY -> sb.append("    ").append(member.name()).append(": ")
                            .append(member.pyType()).append("  # read-only\n");
                    case METHOD -> {
                        if (methodCounts.get(member.name()) > 1) {
                            sb.append("    @overload\n");
                        }
                        sb.append("    ").append(member.pyType()).append("\n");
                    }
                }
            }
            sb.append("\n");
        }
        var nested = entries.stream().flatMap(entry -> entry.nestedBuilders().stream()).distinct().toList();
        if (!nested.isEmpty()) {
            appendEntries(sb, nested, rendered);
        }
    }
}
