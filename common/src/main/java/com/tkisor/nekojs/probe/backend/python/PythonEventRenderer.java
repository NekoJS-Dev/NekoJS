package com.tkisor.nekojs.probe.backend.python;

import com.tkisor.nekojs.probe.backend.typescript.EventDeclarationGenerator;
import com.tkisor.nekojs.api.ScriptType;
import com.tkisor.nekojs.api.catalog.EventCatalogEntry;
import com.tkisor.nekojs.api.catalog.RegistryBuilderSurfaceEntry;
import com.tkisor.nekojs.api.catalog.RegistryBuilderSurfaceEntry.EventPayload;
import com.tkisor.nekojs.probe.EventPayloadDeclarations;
import com.tkisor.nekojs.api.surface.ApiSymbolId;
import com.tkisor.nekojs.api.surface.ApiTypeRef;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * Renders event declarations from {@link EventCatalogEntry} into Python {@code .pyi} files, mirroring the TS
 * {@code EventDeclarationGenerator}.
 *
 * <p>Produces {@code nekojs/_events/<side>/__init__.pyi}: one class per event group, named with the group name
 * plus a {@code Type} suffix (for example {@code ServerEventsType}) so it does not clash with the global binding
 * name, and one {@code @staticmethod} per event inside it. For dispatch events it appends an overload that takes
 * the {@code extra} key parameter; in a .pyi a def with the same name is an overload, matching the two
 * signatures on the TS side.
 *
 * <p>Event object types and dispatch key types are best-effort: a SYMBOL the probe did not collect becomes
 * {@code Any}; a dispatch key with an adapter input alias (such as {@code ResourceLocation_}) uses the alias to
 * widen the input type.
 */
public final class PythonEventRenderer {
    private final ApiTypeRefPyRenderer typeR;
    private final Set<String> availableFqns;

    public PythonEventRenderer(ApiTypeRefPyRenderer typeR, Set<String> availableFqns) {
        this.typeR = typeR;
        this.availableFqns = availableFqns;
    }

    /**
     * @param side            target ScriptType, used in the file header comment
     * @param events          events of this side, already filtered by {@code scriptType().test(side)}; must not be
     *                        empty
     * @param adapterAliases  target FQN to adapter input alias, used to widen dispatch keys; may be null
     */
    public String render(ScriptType side, List<EventCatalogEntry> events,
                         Map<String, PythonProbeBackend.PyAdapterAlias> adapterAliases) {
        return render(side, events, adapterAliases, List.of());
    }

    public String render(ScriptType side, List<EventCatalogEntry> events,
                         Map<String, PythonProbeBackend.PyAdapterAlias> adapterAliases,
                         List<RegistryBuilderSurfaceEntry> builders) {
        Map<Class<?>, EventPayload> payloads = EventPayloadDeclarations.resolve(events, builders);
        // 1. Collect imports: event types plus dispatch key types and aliases
        Set<String> reserved = new LinkedHashSet<>(List.of("Any", "Callable", "overload", "Protocol", "Literal"));
        events.forEach(event -> reserved.add(groupTypeName(event.group())));
        payloads.values().forEach(payload -> reserved.add(payload.name()));
        List<String> builderNames = EventPayloadDeclarations.builderNames(payloads, builders);
        reserved.addAll(builderNames);
        PythonImports importByName = new PythonImports(reserved, typeR);
        List<EventInfo> infos = new ArrayList<>();
        for (EventCatalogEntry e : events) {
            EventPayload payload = payloads.get(e.eventType());
            String eventType = payload == null ? renderClass(e.eventType(), importByName) : payload.name();
            String keyType = null;
            if (e.dispatchable() && e.dispatchKeyType() != null) {
                keyType = renderKey(e.dispatchKeyType(), adapterAliases, importByName);
            }
            infos.add(new EventInfo(e, eventType, keyType));
        }

        // 2. File header, typing imports, cross-package imports
        StringBuilder sb = new StringBuilder();
        sb.append("# Auto-generated by NekoJS probe — Python stubs for ").append(side.name).append(" events.\n");
        sb.append("# Do not edit; regenerate with `/nekojs probe python`.\n\n");
        // overload is always imported even with no dispatch events; an unused name is no error in a stub.
        sb.append("from typing import Any, Callable, overload")
                .append(payloads.isEmpty() ? "" : ", Protocol");
        if (payloads.values().stream().flatMap(payload -> payload.members().stream())
                .anyMatch(member -> member.pyType().contains("Literal["))) {
            sb.append(", Literal");
        }
        sb.append('\n');
        if (!builderNames.isEmpty()) {
            sb.append("from nekojs._registry_builders import ").append(String.join(", ", builderNames)).append("\n");
        }
        importByName.appendTo(sb);

        for (EventPayload payload : payloads.values()) {
            sb.append("\nclass ").append(payload.name()).append("(Protocol):\n");
            if (payload.members().isEmpty()) {
                sb.append("    ...\n");
            }
            Map<String, Long> methodCounts = payload.members().stream()
                    .filter(member -> member.kind() == RegistryBuilderSurfaceEntry.MemberKind.METHOD)
                    .collect(Collectors.groupingBy(RegistryBuilderSurfaceEntry.Member::name, Collectors.counting()));
            for (RegistryBuilderSurfaceEntry.Member member : payload.members()) {
                switch (member.kind()) {
                    case WRITABLE_PROPERTY -> sb.append("    ").append(member.name()).append(": ")
                            .append(member.pyType()).append("\n");
                    case READ_ONLY_PROPERTY -> sb.append("    ").append(member.name()).append(": ")
                            .append(member.pyType()).append("  # read-only\n");
                    case METHOD -> {
                        if (methodCounts.get(member.name()) > 1) {
                            sb.append("    @overload\n");
                        }
                        sb.append("    ").append(member.pyType()).append("\n");
                    }
                }
            }
        }

        // 3. Group by group, keeping the order events appear in; each group becomes one <Group>Type class
        Map<String, List<EventInfo>> byGroup = infos.stream().collect(
                Collectors.groupingBy(i -> i.entry().group(), LinkedHashMap::new, Collectors.toList()));
        for (var groupEntry : byGroup.entrySet()) {
            sb.append("\nclass ").append(groupTypeName(groupEntry.getKey())).append(":\n");
            for (EventInfo info : groupEntry.getValue()) {
                String name = PythonClassRenderer.pyIdent(info.entry().name());
                if (info.entry().scriptDefined()) {
                    // Custom events declared by ScriptEvents: the payload is Any and the script may fire them itself.
                    // Python has no namespace merging (the TS function plus namespace), so a nested class plus a
                    // same-named instance annotation expresses both "callable to listen" and "has a post member to
                    // fire". Same source as the scriptDefined rendering in the TS EventDeclarationGenerator (any
                    // payload plus post).
                    sb.append("    class ").append(name).append(":\n");
                    sb.append("        def __call__(self, handler: Callable[[Any], None]) -> None: ...\n");
                    sb.append("        def post(self, payload: Any = ...) -> None: ...\n");
                    sb.append("    ").append(name).append(": ").append(name).append("\n");
                } else if (info.keyType() != null) {
                    // Both signatures of a dispatch event must be declared with @overload: in a .pyi, two bare defs
                    // with the same name and different parameters make Pylance/pyright report reportRedeclaration
                    // ("method declaration obscured by same-name declaration").
                    sb.append("    @staticmethod\n");
                    sb.append("    @overload\n");
                    sb.append("    def ").append(name)
                      .append("(handler: Callable[[").append(info.eventType()).append("], None]) -> None: ...\n");
                    sb.append("    @staticmethod\n");
                    sb.append("    @overload\n");
                    sb.append("    def ").append(name).append("(extra: ").append(info.keyType())
                      .append(", handler: Callable[[").append(info.eventType()).append("], None]) -> None: ...\n");
                } else {
                    sb.append("    @staticmethod\n");
                    sb.append("    def ").append(name)
                      .append("(handler: Callable[[").append(info.eventType()).append("], None]) -> None: ...\n");
                }
            }
        }
        return sb.toString();
    }

    /**
     * Python class name for an event group: the group name plus a {@code Type} suffix (for example
     * {@code ServerEventsType}).
     */
    static String groupTypeName(String group) {
        return PythonClassRenderer.pyIdent(group) + "Type";
    }

    /**
     * Event object type: when the SYMBOL is available, import it and use the simple name; otherwise the renderer
     * falls back to Any.
     */
    private String renderClass(Class<?> cls, PythonImports importByName) {
        if (cls == null) return "Any";
        ApiTypeRef ref = classToTypeRef(cls);
        importSymbolIfAvailable(ref, importByName);
        return typeR.withSymbolNames(importByName.typeNames()).render(ref);
    }

    /** Dispatch key type: use the adapter alias when one exists, to widen the input; otherwise render normally. */
    private String renderKey(Class<?> cls, Map<String, PythonProbeBackend.PyAdapterAlias> adapterAliases,
                             PythonImports importByName) {
        ApiTypeRef ref = classToTypeRef(cls);
        if (ref.kind() == ApiTypeRef.Kind.SYMBOL) {
            String fqn = ApiTypeRefPyRenderer.extractFqn(ref.name());
            PythonProbeBackend.PyAdapterAlias alias = adapterAliases == null ? null : adapterAliases.get(fqn);
            if (alias != null) {
                return importByName.symbol(fqn, alias.aliasName());
            }
        }
        importSymbolIfAvailable(ref, importByName);
        return typeR.withSymbolNames(importByName.typeNames()).render(ref);
    }

    private void importSymbolIfAvailable(ApiTypeRef ref, PythonImports importByName) {
        Set<String> symbols = new java.util.TreeSet<>();
        ApiTypeRefPyRenderer.collectSymbolFqns(ref, symbols);
        for (String fqn : symbols) if (availableFqns.contains(fqn)) importByName.type(fqn);
    }

    /**
     * Maps a {@code Class<?>} to an {@link ApiTypeRef}, mirroring TypeReflector.classToRef on a best-effort basis.
     */
    static ApiTypeRef classToTypeRef(Class<?> cls) {
        if (cls == void.class || cls == Void.class) return ApiTypeRef.voidType();
        if (cls == String.class || cls == char.class || cls == Character.class) return ApiTypeRef.primitive("string");
        if (cls == boolean.class || cls == Boolean.class) return ApiTypeRef.primitive("boolean");
        if (cls == float.class || cls == Float.class || cls == double.class || cls == Double.class) {
            return ApiTypeRef.primitive("float");
        }
        if (cls.isPrimitive() || Number.class.isAssignableFrom(cls)) return ApiTypeRef.primitive("int");
        if (cls == Object.class) return ApiTypeRef.primitive("object");
        if (cls.isArray()) return ApiTypeRef.array(classToTypeRef(cls.getComponentType()));
        return ApiTypeRef.symbol(new ApiSymbolId("java", cls.getName()));
    }

    /**
     * Render info for one event: the entry plus the rendered event type and dispatch key type (null means no key
     * overload).
     */
    private record EventInfo(EventCatalogEntry entry, String eventType, String keyType) {}
}
